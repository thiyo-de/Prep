import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const fontkit = require('@foliojs-fork/fontkit');
const roboto = require('pdfmake/build/vfs_fonts.js');
const root = new URL('../', import.meta.url);
const definitions = {
  Tamil: { normal: 'NotoSansTamil-Regular.ttf', bold: 'NotoSansTamil-Bold.ttf', italics: 'NotoSansTamil-Regular.ttf', bolditalics: 'NotoSansTamil-Bold.ttf' },
  Mono: { normal: 'NotoSansMono-Regular.ttf', bold: 'NotoSansMono-Bold.ttf', italics: 'NotoSansMono-Regular.ttf', bolditalics: 'NotoSansMono-Bold.ttf' },
  Symbols: Object.fromEntries(['normal', 'bold', 'italics', 'bolditalics'].map(style => [style, 'NotoSansSymbols2-Regular.ttf']))
};
const vfs = {}, coverage = {};
for (const [family, styles] of Object.entries({ Roboto: { normal: 'Roboto-Regular.ttf', bold: 'Roboto-Medium.ttf', italics: 'Roboto-Italic.ttf', bolditalics: 'Roboto-MediumItalic.ttf' }, ...definitions })) {
  let supported;
  for (const file of new Set(Object.values(styles))) {
    const bytes = family === 'Roboto' ? Buffer.from(roboto[file], 'base64') : await readFile(new URL(`fonts/${file}`, root));
    if (family !== 'Roboto') vfs[file] = bytes.toString('base64');
    const chars = new Set(fontkit.create(bytes).characterSet);
    supported = supported ? new Set([...supported].filter(code => chars.has(code))) : chars;
  }
  coverage[family] = [...supported].sort((a, b) => a - b);
}
await mkdir(new URL('src/generated/', root), { recursive: true });
await writeFile(new URL('src/generated/pdf-fonts.js', root), `// Generated by scripts/build-pdf-fonts.mjs. Do not edit.\nexport const vfs = ${JSON.stringify(vfs)};\nexport const definitions = ${JSON.stringify(definitions)};\nexport const coverage = ${JSON.stringify(coverage)};\n`);
console.log('Prepared embedded Tamil, monospace and symbol fonts for PDF export.');
